"""Frozen explained-addition diagnostics, including valid intermediate steps.

Every model gets the same worked example. These are small BASE completion
checks, not a general reasoning benchmark. Test operands are disjoint from the
verified curriculum generated by build_reasoning_curriculum.py.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path
import signal
import sys
import time

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

SEALED_PAIRS = [(169, 70), (191, 61), (100, 19), (121, 66), (127, 66), (181, 14), (134, 12), (189, 28), (184, 93), (173, 62), (166, 55), (137, 12), (181, 85), (116, 23), (175, 54), (107, 68), (125, 61), (101, 59), (139, 41), (166, 15), (112, 57), (124, 88), (126, 54), (183, 73), (122, 77), (123, 36), (176, 59), (128, 11), (138, 81), (144, 77), (192, 49), (171, 34)]
DEMONSTRATION = ("Problem: Add 14 and 22.\nSolution: Separate tens and units. "
                 "Tens: 10 + 20 = 30. Units: 4 + 2 = 6. Combine: 30 + 6 = 36.\n"
                 "Answer: 36.\n\n")


def reasoning_cases(split='dev'):
    if split not in ('dev', 'test'):
        raise ValueError('Unknown split')
    if split == 'dev':
        from scripts.probe_base_learning import build_tasks
        from scripts.eval_base_readiness import cases
        _, tasks = build_tasks(worked_examples=True)
        pairs = [tuple(r['pair'][1:]) for r in tasks
                 if r['category'] == 'arithmetic_equation' and r['pair'][0] == '+']
        pairs += [tuple(r['operands']) for r in cases('dev') if r['category'] == 'equation']
    else:
        pairs = SEALED_PAIRS
    rows = []
    for i, (a,b) in enumerate(pairs):
        for style in ('equation', 'word'):
            if split == 'dev':
                problem = (f'Find the sum of {a} and {b}.' if style == 'equation' else
                           f'A table has {a} red tiles and {b} blue tiles. How many tiles are on the table?')
            else:
                problem = (f'Determine {a} + {b}.' if style == 'equation' else
                           f'A basket holds {a} smooth shells and {b} rough shells. What is the total number of shells?')
            at,bt,au,bu = a//10*10,b//10*10,a%10,b%10
            row = {'id':f"{'explain' if split == 'dev' else 'sealed'}_{style}_{i}",
                   'category':'reasoned_'+style,
                   'prompt':DEMONSTRATION+'Problem: '+problem+'\nSolution:',
                   'answer':str(a+b),
                   'expected_equations':[[at,bt,at+bt],[au,bu,au+bu],[at+bt,au+bu,a+b]],
                   'max_new_tokens':128}
            if split == 'test':
                row['operands'] = [a,b]
            rows.append(row)
    return rows


def validation_windows(token_count, max_seq_len, seed, split):
    """Keep the historical 128-window split within the model's context limit."""
    import numpy as np
    if split not in ('dev', 'test'):
        raise ValueError('Unknown validation split')
    seq_len = min(2048, max_seq_len)
    if seq_len < 1:
        raise ValueError('Model context length must be positive')
    available = (token_count - 1) // seq_len
    if available < 128:
        raise ValueError(f'Validation array needs at least {128 * seq_len + 1} tokens '
                         f'for 128 windows of {seq_len}; got {token_count}')
    indices = np.random.default_rng(seed).choice(available, size=128, replace=False)
    return seq_len, indices[:32] if split == 'dev' else indices[32:]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--checkpoint', type=Path, required=True)
    parser.add_argument('--tokenizer', type=Path, required=True)
    parser.add_argument('--output', type=Path, required=True)
    parser.add_argument('--split', choices=['dev','test'], default='dev')
    parser.add_argument('--tasks', type=Path, help='Optional frozen task JSON instead of the built-in explained-addition suite')
    parser.add_argument('--validation-array', type=Path, help='Optional held-out token array for general-language NLL')
    parser.add_argument('--validation-split', choices=['dev','test'], default='dev')
    parser.add_argument('--validation-seed', type=int, default=20260922,
                        help='Seed for fixed validation windows; freeze before comparing checkpoints')
    args = parser.parse_args()
    if args.output.exists():
        parser.error('Output exists; preserve earlier evidence and choose a new path')
    stopped = False
    def interrupt(_sig, _frame):
        nonlocal stopped
        stopped = True
    signal.signal(signal.SIGINT, interrupt)
    import hashlib
    import numpy as np
    import mlx.core as mx
    from scripts.probe_base_learning import digest
    from scripts._base_probe_cases import SCORING_VERSION, score_completion, is_base_checkpoint
    from scripts.build_reasoning_curriculum import REASONING_SCORING_VERSION, score_reasoned_completion, addition_claim_diagnostics
    from runtime.checkpoint_io import (load_mlx_checkpoint_config, load_mlx_checkpoint_meta,
        load_mlx_model_weights_strict, validate_checkpoint_tokenizer)
    from runtime.mlx_backend import load_safetensors
    from model.transformer_mlx import SpakieGPTMLX
    from tokenizer.train_tokenizer import SpakieTokenizer
    from inference.generate_mlx import generate
    metadata = load_mlx_checkpoint_meta(str(args.checkpoint))
    if not is_base_checkpoint(metadata, args.checkpoint):
        parser.error('This diagnostic requires a BASE pretrain checkpoint')
    validate_checkpoint_tokenizer(metadata, str(args.tokenizer), source=str(args.checkpoint))
    model = SpakieGPTMLX(load_mlx_checkpoint_config(str(args.checkpoint)))
    load_mlx_model_weights_strict(model, load_safetensors(str(args.checkpoint)), path=str(args.checkpoint))
    model.eval()
    mx.eval(model.parameters())
    tokenizer = SpakieTokenizer(str(args.tokenizer))
    tasks = json.loads(args.tasks.read_text()) if args.tasks else reasoning_cases(args.split)
    result = {'status':'running', 'checkpoint_sha256':digest(args.checkpoint),
              'tokenizer_sha256':digest(args.tokenizer), 'scoring_version':SCORING_VERSION,
              'reasoning_scoring_version':REASONING_SCORING_VERSION,
              'task_sha256':hashlib.sha256(json.dumps(tasks, sort_keys=True).encode()).hexdigest(),
              'script_sha256':digest(__file__), 'metrics':{}, 'records':[]}
    args.output.parent.mkdir(parents=True, exist_ok=True)
    start = time.monotonic()
    def save():
        args.output.write_text(json.dumps(result, indent=2)+'\n')
    try:
        if args.validation_array and not stopped:
            val = np.load(args.validation_array, mmap_mode='r')
            if val.ndim != 1 or not np.issubdtype(val.dtype, np.integer):
                raise ValueError('Validation array must contain a one-dimensional integer token stream')
            seq_len, indices = validation_windows(len(val), model.config.max_seq_len,
                                                 args.validation_seed, args.validation_split)
            result['validation_seq_len'] = seq_len
            losses = []
            for index in indices:
                if stopped:break
                chunk = np.array(val[int(index)*seq_len:int(index)*seq_len+seq_len+1], dtype=np.int32)
                _, loss, _ = model(mx.array(chunk[:-1][None]), targets=mx.array(chunk[1:][None]))
                losses.append(float(loss.item()))
            result.update(validation_indices=indices[:len(losses)].tolist(), window_nll=losses,
                          mean_nll=float(np.mean(losses)) if losses else None,
                          validation_array=str(args.validation_array.resolve()), validation_split=args.validation_split,
                          validation_seed=args.validation_seed)
        for row in tasks:
            if stopped:break
            ids = generate(model, tokenizer, tokenizer.encode(row['prompt']), max_new_tokens=row['max_new_tokens'],
                           temperature=0., top_k=0, top_p=1., repetition_penalty=1.)
            text = tokenizer.decode(ids)
            record = {**row, 'output':text}
            if 'expected_equations' in row:
                scores = score_reasoned_completion(text, row)
                passed = scores['answer_correct']
                record.update(scores)
                claims = addition_claim_diagnostics(text)
                record.update(claims)
                consistent = scores['steps_correct'] and not claims['invalid_addition_claims']
                record['answer_steps_no_detected_addition_error'] = consistent
                metric = result['metrics'].setdefault(row['category']+'_no_detected_addition_error', {'passed':0,'total':0})
                metric['passed'] += int(consistent); metric['total'] += 1
                metric = result['metrics'].setdefault(row['category']+'_valid_steps', {'passed':0,'total':0})
                metric['passed'] += int(scores['steps_correct']); metric['total'] += 1
            else:
                passed = score_completion(text,row)
            record['passed'] = passed
            metric = result['metrics'].setdefault(row['category'], {'passed':0,'total':0})
            metric['passed'] += int(passed); metric['total'] += 1
            result['records'].append(record)
            save()
        result['status'] = 'interrupted' if stopped else 'complete'
    except Exception as exc:
        result.update(status='failed', error=f'{type(exc).__name__}: {exc}')
        raise
    finally:
        result['elapsed_seconds'] = time.monotonic()-start
        save()
    print(json.dumps(result['metrics']), flush=True)
    return 130 if stopped else 0


if __name__ == '__main__':
    try:
        raise SystemExit(main())
    except KeyboardInterrupt:
        print('\nStopped.', file=sys.stderr)
        raise SystemExit(130)
